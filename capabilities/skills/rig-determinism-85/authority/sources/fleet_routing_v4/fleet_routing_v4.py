"""fleet_routing_v4 — immutable deterministic routing authority for the RIG fleet.

Supersedes fleet_routing_v2: v2 was terminally BLOCKed at inventory time
(SOURCE_DYNAMIC_CALL, exit 2) — method calls on call results and on shadowed
locals escape the static execution graph. v2 is preserved as failed evidence;
under the exit-2 rule it is never retried. (v1 BLOCK: module-level Assign
outside the closed module grammar.)

v4 supersedes fleet_routing_v3: v3 was terminally BLOCKed at inventory time
(ZERO_WORK_PROCESS, exit 2) — a bare literal return carries no call-site
stage, so pure-data entrypoints registered as zero-work. v3 is preserved as
failed evidence; under the exit-2 rule it is never retried.

v4 wraps every data table in dict(...)/tuple(...)/int(...): each entrypoint
performs real work and each call returns a FRESH top-level copy, so callers
cannot mutate the authority's tables (shallow; nested records are
caller-trusted).

Design under the closed grammar and the static call graph:

- Every lookup receiver is an inline LITERAL; nested lookups are flattened
  into composite keys ((role, live_plane_tuple)) so one literal .get answers.
- Set algebra uses Set-literal receivers only ({"P1",...}.difference(...)).
- All table functions are TOTAL (unknown role/endpoint/plane yields
  "" / {} / () / False instead of v1's KeyError).
- ROUTE_TABLE / TWO_PLANES_TABLE were GENERATED from v1's route_for_role /
  role_has_two_planes over all 16 live-plane sets x 8 roles and verified
  cell-for-cell against v1 (incl. unknown-plane noise) before writing.
- All threshold COMPARISONS stay in the executor/monitor. The authority
  exposes limits, never verdicts. Executor contract (v1 check_endpoint
  semantics): FAIL when ttft_s > ttft_s_fail; else DEGRADED when
  ttft_s > ttft_s_max or tps < tps_min; else PASS. Paid lane: stop when
  quota_pct >= paid_quota_stop_pct().
- planes_down arguments name DOWN planes (v1 semantics); route keys are the
  derived LIVE-plane tuples, sorted-canonical. Unknown plane ids in
  planes_down are ignored (v1-equivalent).

# ponytail: tables rebuild per call because the grammar forbids module-level
# constants; O(tiny) literals — revisit only if a profiler names this hot.
# Any content change requires a NEW process-id (fleet_routing_v5, ...).
"""


