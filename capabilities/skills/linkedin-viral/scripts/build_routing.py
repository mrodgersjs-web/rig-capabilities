#!/usr/bin/env python3
"""Regenerate references/routing.md (v2) from references/stage-map.json and the lv-* stage skills.

Only paths that exist on disk are backticked, so check_routes.py stays an honest gate:
a missing file is listed as plain text under 'Broken or phantom', never as a route.
"""
import json, os, pathlib, re

LV = pathlib.Path(__file__).resolve().parent.parent
SK = LV.parent
H = os.path.expanduser("~")
rows = json.load(open(LV / "references" / "stage-map.json"))
STAGES = ["lv-strategy", "lv-plan", "lv-hooks", "lv-draft", "lv-visuals", "lv-gate",
          "lv-launch", "lv-engage", "lv-outreach", "lv-profile", "lv-measure", "lv-distribute"]


def tilde(p):
    return p.replace(H, "~") if p else p


def exists(p):
    return bool(p) and not p.startswith("eden://") and os.path.exists(os.path.expanduser(p))


def cell(p):
    return f"`{tilde(p)}`" if exists(p) else (f"Eden skill ({p.split('/')[-1]})" if p.startswith("eden://") else f"MISSING {tilde(p)}")


def desc_of(stage):
    f = SK / stage / "SKILL.md"
    if not f.exists():
        return "(stage skill not built)"
    t = f.read_text(encoding="utf-8")
    m = re.search(r"description: >-\n((?:[ \t]+.*\n)+)", t)
    d = " ".join(m.group(1).split()) if m else ""
    return d.split(" JEV-FIRST")[0][:230].replace("|", "/")


out = ["# linkedin-viral: routing table v2 (12 stages)", "",
       "Generated by `scripts/build_routing.py` from `references/stage-map.json`. Load the ONE stage that owns the job; the stage lists its own tools, runners and sub-skills. Legacy skills below are SUPERSEDED for routing: their content was merged into the stage named. They stay on disk because agents and crons still load some of them (see the prune folder's dependents list).", "",
       "## The 12 stages", "", "| stage | path | owns | merged | tools | runners |", "|---|---|---|---|---|---|"]
for s in STAGES:
    rs = [r for r in rows if r.get("stage") == s]
    c = {k: sum(1 for r in rs if r["role"] == k) for k in ("merge", "tool", "runner")}
    out.append(f"| {s} | `~/Developer/rig-capabilities/capabilities/skills/{s}/SKILL.md` | {desc_of(s)} | {c['merge']} | {c['tool']} | {c['runner']} |")
out += ["", "Doctrine source for every stage: `~/Developer/rig-capabilities/capabilities/skills/tommy-clark-doctrine/SKILL.md` (79 videos, dated rule ledger).", ""]
for s in STAGES:
    rs = sorted([r for r in rows if r.get("stage") == s and r["role"] in ("merge", "tool", "runner")], key=lambda r: (r["role"], r["id"]))
    out += [f"## {s}: legacy assets", "", "| id | role | path | status |", "|---|---|---|---|"]
    for r in rs:
        status = {"merge": f"superseded by {s}", "tool": f"called by {s}", "runner": f"runner; should call {s}"}[r["role"]]
        out.append(f"| {r['id']} | {r['role']} | {cell(r.get('path', ''))} | {status} |")
    out.append("")
routers = [r for r in rows if r["role"] == "router"]
out += ["## Superseded routers (linkedin-viral is the front door now)", "", "| id | path |", "|---|---|"]
out += [f"| {r['id']} | {cell(r['path'])} |" for r in sorted(routers, key=lambda r: r["id"])]
out += ["", "## Retired: never route (Postiz retired 2026-09-17; Eden is the only publisher)", "", "| id | path |", "|---|---|"]
out += [f"| {r['id']} | {cell(r['path'])} |" for r in sorted([r for r in rows if r["role"] == "retired"], key=lambda r: r["id"])]
out += ["", "## Broken or phantom: report, never improvise", ""]
out += [f"- {r['id']}: {tilde(r['path'])} (no readable file)" for r in sorted([r for r in rows if r["role"] == "broken"], key=lambda r: r["id"])]
out += ["", "## Adjacent lanes: never route LinkedIn work here", "", "| id | why | path |", "|---|---|---|",
        "| jacob-x-growth | content about a minor (Jacob, X account); per-post approval, never auto-scheduled | `~/.aside/u/0/skills/user/jacob-x-growth/SKILL.md` |",
        "| rig-instagram-growth | Instagram lane (@rodgemd1) | `~/.aside/u/0/skills/user/rig-instagram-growth/SKILL.md` |",
        "| when-selling-or-running-gtm | cold email and multi-channel GTM skills that merely mention LinkedIn (13 found in the 2026-09-28 audit) | `~/.aside/u/0/skills/user/when-selling-or-running-gtm/SKILL.md` |", ""]
(LV / "references" / "routing.md").write_text("\n".join(out) + "\n", encoding="utf-8")
print("routing.md lines:", len(out))
