OUTCOMES = [r[0] for r in RULES]
KIND_DEFAULTS = {"hook": "agent-engineering", "loop": "agent-engineering"}
SOURCE_PREF = ["canonical", "claude-skills", "agents-skills", "omp", "codex-skills",
               "hermes-skills"]


def _id_hit(aid: str, subs) -> bool:
    return any(s in aid for s in subs)


def classify(asset: dict) -> str:
    """Return the outcome lane for one index asset (deterministic)."""
    if asset.get("lane"):
        return asset["lane"]
    aid = asset["id"].lower()
    for outcome, _desc, subs, dregex in RULES:
        if _id_hit(aid, subs):
            return outcome
    text = (asset.get("description") or "").lower()
    for outcome, _desc, _subs, dregex in RULES:
        if dregex and re.search(dregex, text):
            return outcome
    if asset["kind"] in KIND_DEFAULTS:
        return KIND_DEFAULTS[asset["kind"]]
    if asset["kind"] == "agent":
        return "agent-engineering"
    return "misc"


def dedupe(assets) -> list:
    """One entry per (kind, id), source-pref order preserved by index order."""
    order = {s: i for i, s in enumerate(SOURCE_PREF)}
    best: dict = {}
    for a in assets:
        k = (a["kind"], a["id"])
        cur = best.get(k)
        if cur is None:
            best[k] = a
        else:
            rank = lambda s: order.get(s, len(SOURCE_PREF))
            if rank(a["source"]) < rank(cur["source"]):
                best[k] = a
    return list(best.values())


def outcome_counts(assets) -> "OrderedDict[str, dict]":
    per: dict = {}
    for a in assets:
        o = classify(a)
        per.setdefault(o, Counter())[a["kind"]] += 1
    keys = OUTCOMES + [o for o in per if o not in OUTCOMES]
    out = OrderedDict()
    for o in keys:
        if o in per:
            out[o] = {"total": sum(per[o].values()), "kinds": dict(per[o])}
    return out


def build_tree(repo, out_dir: Path | None = None) -> dict:
    """Materialize tree/<outcome>/<kind>/<id> symlinks + INDEX.md files.

    Built into a sibling `<out>.new/` dir, swapped via rename; the previous
    tree is moved aside as `<out>.old/` then removed — nothing is deleted
    outside the generated tree itself.
    """
    doc = repo.load_index()
    assets = dedupe(doc["assets"])
    out_dir = Path(out_dir) if out_dir else Path(repo.root) / "tree"
    new = out_dir.with_name(out_dir.name + ".new")
    old = out_dir.with_name(out_dir.name + ".old")
    if new.exists():
        shutil.rmtree(new)
    new.mkdir(parents=True)

    per: dict = {}
    for a in assets:
        o = classify(a)
        per.setdefault(o, []).append(a)

    for outcome, rows in sorted(per.items()):
        od = new / outcome
        for kind in sorted({r["kind"] for r in rows}):
            (od / kind).mkdir(parents=True, exist_ok=True)
        lines = [f"# {outcome} — {len(rows)} capabilities", ""]
        for r in sorted(rows, key=lambda x: (x["kind"], x["id"])):
            link = od / r["kind"] / r["id"]
            if not link.exists():
                os.symlink(r["abs_path"], str(link))
            desc = (r["description"] or "")[:110].replace("\n", " ")
            lines.append(f"- `{r['kind']}` **{r['id']}** [{r['source']}] — {desc}")
        kc = Counter(r["kind"] for r in rows)
        head = "\n".join(f"- {k}: {v}" for k, v in sorted(kc.items()))
        (od / "INDEX.md").write_text(
            f"# outcome: {outcome}\n\n{dict(RULES_MAP).get(outcome, 'Unclassified — review and add a rule.')}\n\n"
            f"counts: {dict(sorted(kc.items()))}\n\n{head}\n\n" + "\n".join(lines) + "\n")

    counts = outcome_counts(assets)
    tbl = ["| outcome | total | kinds |", "|---|---|---|"]
    for o, c in counts.items():
        tbl.append(f"| [{o}]({o}/INDEX.md) | {c['total']} | "
                   + ", ".join(f"{k}×{v}" for k, v in sorted(c["kinds"].items())) + " |")
    (new / "AGENT-INDEX.md").write_text(
        "# Capability tree — browse by outcome\n\n"
        "Each leaf is a symlink to the real asset directory. Start at an "
        "outcome INDEX.md, then read the skill/harness file directly.\n\n"
        + "\n".join(tbl) + "\n")

    if out_dir.exists():
        if old.exists():
            shutil.rmtree(old)
        os.rename(out_dir, old)
        os.rename(new, out_dir)
        shutil.rmtree(old)
    else:
        os.rename(new, out_dir)
    return {"outcomes": len(per), "assets": len(assets), "tree": str(out_dir)}


RULES_MAP = [(r[0], r[1]) for r in RULES]

_QUERY_STOP = set("a an the for and or of to in on with my our me how make using".split())

_QUERY_STOP |= {"this", "that", "these", "those", "it", "its", "them", "they",
                "i", "you", "we", "want", "need", "wanting", "give", "get"}


def route(repo, query: str, per: int = 5) -> dict:
    """Intent -> ranked outcome lanes + representative capabilities."""
    doc = repo.load_index()
    assets = dedupe(doc["assets"])
    toks = [t for t in re.split(r"[^a-z0-9]+", query.lower()) if t and t not in _QUERY_STOP]
    ids = [a["id"].lower() for a in assets]
    descs = [(a.get("description") or "").lower() for a in assets]
    # Inverse-document-frequency: a token in few ids is specific ('threat');
    # a token in hundreds ('model', 'api') carries almost no signal.
    w_id = {t: 10.0 / (1 + sum(1 for s in ids if t in s)) for t in toks}
    w_desc = {t: 2.0 / (1 + sum(1 for s in descs if t in s)) for t in toks}
    lane_top: dict = {}
    lane_sum: Counter = Counter()
    hits: dict = {}
    for a, aid, desc in zip(assets, ids, descs):
        o = classify(a)
        s = 0.0
        for t in toks:
            if t in aid:
                s += w_id[t]
            elif t in desc:
                s += w_desc[t]
        if s:
            lane_sum[o] += s
            lane_top[o] = max(lane_top.get(o, 0.0), s)
            hits.setdefault(o, []).append((s, a))
    out = []
    # Rank by the best single match (peak relevance); total match mass is a
    # tiebreaker, so a lane with one precise hit beats one with many weak hits.
    order = sorted(lane_top, key=lambda o: (-lane_top[o], -lane_sum[o]))
    for o in order:
        rows = sorted(hits[o], key=lambda x: -x[0])[:per]
        out.append({"outcome": o, "score": round(lane_top[o], 3),
                    "capabilities": [{"id": a["id"], "kind": a["kind"],
                                      "source": a["source"], "description":
                                      (a["description"] or "")[:140]} for _s, a in rows]})
    return {"query": query, "lanes": out}
